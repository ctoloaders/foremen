package com.foremen.service.roomsimport;

import java.time.Duration;
import java.time.Instant;
import java.util.Collection;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

import org.springframework.stereotype.Component;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;
import org.springframework.web.multipart.MultipartFile;

import com.foremen.service.document.pdf.InMemoryMultipartFile;
import com.foremen.service.image.ImageStorage;

import lombok.extern.slf4j.Slf4j;

/**
 * FOR-05-02 (Requirements 9.1, 14.3, 24.7) — the job-scoped view of the {@link ImageStorage} seam.
 * Inputs live under {@code rooms-import/{jobId}/in/}, draft media under
 * {@code rooms-import/{jobId}/media/}; keys are always generated by the storage (never from client
 * names). Deletions are best-effort and, inside a transaction, deferred until after commit.
 */
@Slf4j
@Component
public class RoomsImportStorage {

    /** Root namespace of every rooms-import object. */
    public static final String ROOT_PREFIX = "rooms-import/";

    private final ImageStorage imageStorage;

    public RoomsImportStorage(ImageStorage imageStorage) {
        this.imageStorage = imageStorage;
    }

    public boolean isConfigured() {
        return imageStorage.isConfigured();
    }

    /** Stores an uploaded input; returns the generated object key. */
    public String storeInput(Long jobId, MultipartFile file) {
        return imageStorage.storeObject(file, RoomsImportErrors.jobNamespace(jobId) + "/in");
    }

    /** Stores a draft media image; returns the generated object key. */
    public String storeMedia(Long jobId, byte[] bytes, String contentType) {
        return imageStorage.storeObject(new InMemoryMultipartFile("media", "room", contentType, bytes),
                RoomsImportErrors.jobNamespace(jobId) + "/media");
    }

    public byte[] read(String objectKey) {
        return imageStorage.readObject(objectKey);
    }

    /** Deletes the keys after the current transaction commits (immediately when there is none). */
    public void deleteAfterCommit(Collection<String> keys) {
        if (keys == null || keys.isEmpty()) {
            return;
        }
        Set<String> copy = new LinkedHashSet<>(keys);
        runAfterCommit(() -> deleteNow(copy));
    }

    /**
     * Deletes the given keys plus every object found under the job's prefix (catches draft media written
     * after the job row was gone), after the current transaction commits. Best effort.
     */
    public void deleteJobObjectsAfterCommit(Long jobId, Collection<String> knownKeys) {
        Set<String> copy = knownKeys == null ? Set.of() : new LinkedHashSet<>(knownKeys);
        runAfterCommit(() -> {
            deleteNow(copy);
            deleteJobPrefix(jobId);
        });
    }

    /** Deletes everything under {@code rooms-import/{jobId}/}. */
    public void deleteJobPrefix(Long jobId) {
        try {
            List<ImageStorage.StoredObject> found =
                    imageStorage.listObjects(RoomsImportErrors.jobNamespace(jobId) + "/");
            deleteNow(found.stream().map(ImageStorage.StoredObject::key).toList());
        } catch (RuntimeException e) {
            log.warn("Failed to list rooms-import objects of job {}: {}", jobId, e.getMessage());
        }
    }

    /** All objects under the root prefix (orphan sweep). */
    public List<ImageStorage.StoredObject> listAll() {
        return imageStorage.listObjects(ROOT_PREFIX);
    }

    /** True when the object is older than {@code minAge} (unknown creation time counts as old). */
    public static boolean olderThan(ImageStorage.StoredObject object, Duration minAge, Instant now) {
        return object.createdAt() == null || object.createdAt().isBefore(now.minus(minAge));
    }

    public void deleteNow(Collection<String> keys) {
        for (String key : keys) {
            try {
                imageStorage.deleteIfOrphan(key);
            } catch (RuntimeException e) {
                log.warn("Failed to delete rooms-import object {}: {}", key, e.getMessage());
            }
        }
    }

    private static void runAfterCommit(Runnable action) {
        if (TransactionSynchronizationManager.isSynchronizationActive()) {
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override
                public void afterCommit() {
                    action.run();
                }
            });
        } else {
            action.run();
        }
    }
}
