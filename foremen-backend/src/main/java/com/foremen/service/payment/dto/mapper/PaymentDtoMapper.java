package com.foremen.service.payment.dto.mapper;

import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

import com.foremen.config.mapper.ForemenMapperConfig;
import com.foremen.dao.model.PaymentScheduleEntity;
import com.foremen.dao.model.PaymentTrancheEntity;
import com.foremen.dao.model.PaymentTransactionEntity;
import com.foremen.dao.model.TrancheAllocationEntity;
import com.foremen.service.payment.dto.PaymentScheduleView;
import com.foremen.service.payment.dto.PaymentTrancheDto;
import com.foremen.service.payment.dto.PaymentTransactionDto;
import com.foremen.service.payment.dto.TrancheAllocationDto;

/**
 * FOR-06-07 (Requirement 1.4): MapStruct read mapper from the payment entity graph
 * ({@code PaymentScheduleEntity}, {@code PaymentTrancheEntity}, {@code PaymentTransactionEntity},
 * {@code TrancheAllocationEntity}) to the read DTOs of {@code com.foremen.service.payment.dto}.
 * Spring component (via {@link ForemenMapperConfig}); builder-less, so records are populated through
 * their canonical constructors.
 *
 * <p>The scalar entity→DTO maps are generated by MapStruct. The aggregate {@link PaymentScheduleView}
 * is assembled by the {@link #toView(PaymentScheduleEntity)} default method, which <b>computes</b> the
 * derived figures from the mapped tranches: {@code sumAmountGross = Σ amountGross},
 * {@code sumPaidGross = Σ paidGross}, and {@code unpaidRemainder = basisGross − sumPaidGross}
 * (clamped at zero so a schedule overpaid relative to its basis never reports a negative remainder,
 * R1.4, R6.3). The tranches are ordered by {@code seqNo}. The {@code status}/{@code source} enums are
 * copied through — derivation of {@code status} happens upstream in {@code TrancheStatusDeriver}; this
 * mapper only renders the materialized cache (R1.6, R10.3).
 */
@Mapper(config = ForemenMapperConfig.class)
public interface PaymentDtoMapper {

    PaymentTrancheDto toDto(PaymentTrancheEntity entity);

    List<PaymentTrancheDto> toTrancheDtos(List<PaymentTrancheEntity> entities);

    PaymentTransactionDto toDto(PaymentTransactionEntity entity);

    List<PaymentTransactionDto> toTransactionDtos(List<PaymentTransactionEntity> entities);

    @Mapping(target = "trancheId", source = "tranche.id")
    @Mapping(target = "trancheSeqNo", source = "tranche.seqNo")
    TrancheAllocationDto toDto(TrancheAllocationEntity entity);

    List<TrancheAllocationDto> toAllocationDtos(List<TrancheAllocationEntity> entities);

    /**
     * Assembles the aggregate {@link PaymentScheduleView} from a schedule entity: maps and
     * {@code seqNo}-orders the tranches, then computes the summed and derived figures (R1.4).
     */
    default PaymentScheduleView toView(PaymentScheduleEntity entity) {
        if (entity == null) {
            return null;
        }

        List<PaymentTrancheEntity> ordered = new ArrayList<>(
                entity.getTranches() == null ? List.of() : entity.getTranches());
        ordered.sort(Comparator.comparing(
                PaymentTrancheEntity::getSeqNo, Comparator.nullsLast(Comparator.naturalOrder())));

        List<PaymentTrancheDto> trancheDtos = toTrancheDtos(ordered);

        BigDecimal sumAmountGross = BigDecimal.ZERO;
        BigDecimal sumPaidGross = BigDecimal.ZERO;
        for (PaymentTrancheEntity tranche : ordered) {
            if (tranche.getAmountGross() != null) {
                sumAmountGross = sumAmountGross.add(tranche.getAmountGross());
            }
            if (tranche.getPaidGross() != null) {
                sumPaidGross = sumPaidGross.add(tranche.getPaidGross());
            }
        }

        BigDecimal basisGross = entity.getBasisGross() == null ? BigDecimal.ZERO : entity.getBasisGross();
        BigDecimal unpaidRemainder = basisGross.subtract(sumPaidGross).max(BigDecimal.ZERO);

        BigDecimal unallocatedCredit = entity.getUnallocatedCredit() == null
                ? BigDecimal.ZERO : entity.getUnallocatedCredit();

        return new PaymentScheduleView(
                entity.getId(),
                entity.getProject() == null ? null : entity.getProject().getId(),
                entity.getCurrency(),
                basisGross,
                entity.getSource(),
                entity.getStatus(),
                trancheDtos,
                sumAmountGross,
                sumPaidGross,
                unpaidRemainder,
                unallocatedCredit);
    }
}
