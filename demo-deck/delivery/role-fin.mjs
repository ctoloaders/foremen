import { session } from './shot.mjs';
const s = await session('piotr@loaders.dev');
const { page, snap, go } = s;
await go('/company/bank-transactions');
await snap('fin-01-bank-ledger', { wait: 2000 });
await page.getByText('Przelew za materiały wykończeniowe').first().click();
await snap('fin-02-transaction-detail', { wait: 2000 });
await page.getByRole('button', { name: 'Potwierdź' }).click();
await page.waitForTimeout(2000);
await snap('fin-03-match-confirmed');
await page.keyboard.press('Escape');
await go('/deliveries/external-orders');
await snap('fin-04-orders-queue', { wait: 2000 });
await page.getByRole('button', { name: 'Pokaż szczegóły' }).first().click();
await snap('fin-05-order-details', { wait: 1500 });
await page.getByRole('button', { name: 'Oznacz jako opłacone' }).first().click();
await page.waitForTimeout(800);
await page.getByRole('dialog').getByRole('textbox').last().fill('Przelew mBank 16.11, potwierdzenie w załączniku').catch(() => {});
await snap('fin-06-mark-paid-dialog', { wait: 800 });
await page.getByRole('dialog').getByRole('button', { name: 'Oznacz jako opłacone' }).click();
await page.waitForTimeout(1800);
await snap('fin-07-after-paid');
await page.getByRole('button', { name: 'Opłacone' }).click();
await snap('fin-08-paid-tab', { wait: 1800 });
await page.locator('button:has(svg.lucide-bell)').first().click().catch(() => {});
await snap('fin-09-notifications', { wait: 1500 });
await s.close();
